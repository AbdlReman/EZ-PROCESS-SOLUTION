"use client";

import { useEffect, useRef, useState } from "react";

const PHONE_TEL = "+18433091515";
const PHONE_WA = "18433091515";

export default function LetsTalkButton({
  wrapClassName = "lt-talk-wrap",
  onOptionSelect,
}: {
  wrapClassName?: string;
  onOptionSelect?: () => void;
}) {
  const [open, setOpen] = useState(false);
  const wrapRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (!open) return;
    function onDocClick(e: MouseEvent) {
      if (wrapRef.current && !wrapRef.current.contains(e.target as Node)) {
        setOpen(false);
      }
    }
    function onKey(e: KeyboardEvent) {
      if (e.key === "Escape") setOpen(false);
    }
    document.addEventListener("mousedown", onDocClick);
    window.addEventListener("keydown", onKey);
    return () => {
      document.removeEventListener("mousedown", onDocClick);
      window.removeEventListener("keydown", onKey);
    };
  }, [open]);

  function handleSelect() {
    setOpen(false);
    onOptionSelect?.();
  }

  return (
    <div className={wrapClassName} ref={wrapRef}>
      <button type="button" className="brelyx-btn-talk" onClick={() => setOpen((v) => !v)} aria-expanded={open}>
        Let&apos;s Talk
      </button>

      {open && (
        <div className="lt-talk-popover">
          <a href={`tel:${PHONE_TEL}`} className="lt-talk-option" onClick={handleSelect}>
            <span className="lt-talk-option-icon call">
              <svg width="17" height="17" viewBox="0 0 24 24" fill="none">
                <path
                  d="M22 16.92v3a2 2 0 01-2.18 2 19.79 19.79 0 01-8.63-3.07A19.5 19.5 0 013.07 9.8a19.79 19.79 0 01-3.07-8.68A2 2 0 012 2h3a2 2 0 012 1.72c.127.96.361 1.903.7 2.81a2 2 0 01-.45 2.11L6.09 9.91a16 16 0 006 6l1.27-1.27a2 2 0 012.11-.45c.907.339 1.85.573 2.81.7A2 2 0 0122 16.92z"
                  stroke="currentColor"
                  strokeWidth="1.8"
                  strokeLinecap="round"
                  strokeLinejoin="round"
                />
              </svg>
            </span>
            Call
          </a>
          <a
            href={`https://wa.me/${PHONE_WA}`}
            target="_blank"
            rel="noopener noreferrer"
            className="lt-talk-option"
            onClick={handleSelect}
          >
            <span className="lt-talk-option-icon whatsapp">
              <svg width="17" height="17" viewBox="0 0 24 24" fill="currentColor">
                <path d="M17.472 14.382c-.297-.149-1.758-.867-2.03-.967-.273-.099-.471-.148-.67.15-.197.297-.767.966-.94 1.164-.173.199-.347.223-.644.075-.297-.15-1.255-.463-2.39-1.475-.883-.788-1.48-1.761-1.653-2.059-.173-.297-.018-.458.13-.606.134-.133.298-.347.446-.52.149-.174.198-.298.298-.497.099-.198.05-.371-.025-.52-.075-.149-.669-1.612-.916-2.207-.242-.579-.487-.5-.669-.51-.173-.008-.371-.01-.57-.01-.198 0-.52.074-.792.372-.272.297-1.04 1.016-1.04 2.479 0 1.462 1.065 2.875 1.213 3.074.149.198 2.096 3.2 5.077 4.487.709.306 1.262.489 1.694.625.712.227 1.36.195 1.871.118.571-.085 1.758-.719 2.006-1.413.248-.694.248-1.289.173-1.413-.074-.124-.272-.198-.57-.347z" />
                <path d="M12 0C5.373 0 0 5.373 0 12c0 2.124.558 4.118 1.528 5.845L.057 23.268a.75.75 0 00.923.924l5.484-1.476A11.943 11.943 0 0012 24c6.627 0 12-5.373 12-12S18.627 0 12 0zm0 22c-1.907 0-3.694-.5-5.24-1.378l-.375-.217-3.884 1.046 1.046-3.823-.234-.389A9.959 9.959 0 012 12C2 6.477 6.477 2 12 2s10 4.477 10 10-4.477 10-10 10z" />
              </svg>
            </span>
            WhatsApp
          </a>
        </div>
      )}
    </div>
  );
}
